# Solicite um número inteiro e apresente sua tabuada de multiplicação de 1 até 10 utilizando while.





numero = int(input("digite um numero: "))

contador = 1

while contador <= 10:
    resultado = numero * contador
    print(f"{numero} x {contador} = {resultado}")                                   
    contador += 1
    
print("fim")




